export const SPECIAL_ARTIFACT_ID = "eternal_core";

export const itemTypes = {
  WEAPON: "weapon",
  ARMOR: "armor",
  ARTIFACT: "artifact",
};

export const rarities = {
  COMMON: "common",
  RARE: "rare",
  EPIC: "epic",
  ULTIMATE: "ultimate",
};

export const rarityLabels = {
  [rarities.COMMON]: "Common",
  [rarities.RARE]: "Rare",
  [rarities.EPIC]: "Epic",
  [rarities.ULTIMATE]: "Ultimate",
};

export const classTypes = {
  SINGLE_SWORD: "single_sword",
  GREATSWORD: "greatsword",
  BOW: "bow",
  SPEAR: "spear",
  STAFF: "staff",
};

const allClassTypes = Object.values(classTypes);

const rarityPower = {
  [rarities.COMMON]: 2,
  [rarities.RARE]: 4,
  [rarities.EPIC]: 7,
  [rarities.ULTIMATE]: 12,
};

const createItem = ({
  id,
  name,
  type,
  rarity,
  stats,
  effect,
  passive,
  playstyle,
  classTypes: allowedClassTypes,
  build,
  isActive = false,
  activeCost = 0,
  activeEffect = "",
  isActivated = false,
  isSpecial = false,
  unlockAtLevel,
}) => ({
  id,
  name,
  type,
  rarity,
  rarityLabel: rarityLabels[rarity],
  stats,
  description: passive,
  effect,
  passive,
  playstyle,
  build,
  classTypes: allowedClassTypes,
  powerBonus: rarityPower[rarity],
  isActive,
  activeCost,
  activeEffect,
  isActivated,
  isSpecial,
  unlockAtLevel,
});

const weapon = (id, name, allowedClassTypes, rarity, stats, effect, passive, playstyle) =>
  createItem({
    id,
    name,
    type: itemTypes.WEAPON,
    classTypes: allowedClassTypes,
    rarity,
    stats,
    effect,
    passive,
    playstyle,
  });

const armor = (id, name, rarity, stats, effect, passive, playstyle) =>
  createItem({
    id,
    name,
    type: itemTypes.ARMOR,
    rarity,
    stats,
    effect,
    passive,
    playstyle,
  });

const artifact = (id, name, rarity, stats, effect, passive, build, options = {}) =>
  createItem({
    id,
    name,
    type: itemTypes.ARTIFACT,
    rarity,
    stats,
    effect,
    passive,
    build,
    ...options,
  });

